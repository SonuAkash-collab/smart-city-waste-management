"""Run TC-PERF-01 and TC-PERF-02 and write docs/reports/perf-summary.md.

From the backend folder (needs: pip install -r requirements-perf.txt):
    python scripts/run_perf.py [--users 100] [--duration 60]

1. Seeds a separate database (perf.db) with 200 approved requests and 20 vehicles.
2. Starts the API, times POST /routes/generate three times (re-seeding before each run).
3. Runs Locust headless with 100 users and reports how many calls finished within 2 s.
"""

import argparse
import csv
import os
import platform
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import httpx

BACKEND = Path(__file__).resolve().parents[1]
REPORT = BACKEND.parent / "docs" / "reports" / "perf-summary.md"
PORT = 8765
HOST = f"http://127.0.0.1:{PORT}"


def seed(env):
    subprocess.run([sys.executable, "scripts/seed_perf.py"], cwd=BACKEND, env=env, check=True, stdout=subprocess.DEVNULL)


def start_server(env):
    server = subprocess.Popen(
        [sys.executable, "-m", "uvicorn", "app.main:app", "--port", str(PORT), "--log-level", "warning"],
        cwd=BACKEND, env=env,
    )
    for _ in range(50):
        try:
            if httpx.get(f"{HOST}/health", timeout=1).status_code == 200:
                return server
        except httpx.HTTPError:
            time.sleep(0.2)
    server.terminate()
    raise SystemExit("The server did not start.")


def time_generation(env) -> list[float]:
    timings = []
    for run in range(3):
        seed(env)
        server = start_server(env)
        try:
            token = httpx.post(f"{HOST}/api/v1/auth/login", json={"email": "perf.admin@scw.local", "password": "Perf@1234"}).json()["accessToken"]
            started = time.perf_counter()
            response = httpx.post(f"{HOST}/api/v1/routes/generate", json={"date": "2026-11-05"},
                                  headers={"Authorization": f"Bearer {token}"}, timeout=60)
            timings.append(time.perf_counter() - started)
            body = response.json()
            stops = sum(1 for r in body["routes"] for s in r["stops"] if s["stopType"] == "COLLECTION")
            print(f"run {run + 1}: {timings[-1]:.2f} s, {len(body['routes'])} routes, {stops} stops planned")
        finally:
            server.terminate()
            server.wait()
    return timings


def run_locust(env, users: int, duration: int) -> dict:
    seed(env)
    server = start_server(env)
    prefix = BACKEND / "perf"
    try:
        subprocess.run(
            [sys.executable, "-m", "locust", "-f", "tests/perf/locustfile.py", "--headless", "-u", str(users),
             "-r", "10", "-t", f"{duration}s", "--host", HOST, "--csv", str(prefix), "--only-summary"],
            cwd=BACKEND, env=env, check=False,
        )
    finally:
        server.terminate()
        server.wait()
    with open(f"{prefix}_stats.csv", newline="") as handle:
        total = next(row for row in csv.DictReader(handle) if row["Name"] == "Aggregated")
    with open(f"{prefix}_stats_history.csv", newline="") as handle:
        peak_users = max(int(row["User Count"]) for row in csv.DictReader(handle))
    return {
        "requests": int(total["Request Count"]),
        "failures": int(total["Failure Count"]),
        "median": float(total["Median Response Time"]),
        "p95": float(total["95%"]),
        "p99": float(total["99%"]),
        "max": float(total["Max Response Time"]),
        "peak_users": peak_users,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--users", type=int, default=100)
    parser.add_argument("--duration", type=int, default=60)
    args = parser.parse_args()
    env = {**os.environ, "DATABASE_URL": "sqlite:///./perf.db", "EMAIL_OUTBOX": os.devnull}

    timings = time_generation(env)
    load = run_locust(env, args.users, args.duration)
    nf1 = max(timings) <= 10
    nf2 = load["p95"] <= 2000 and load["failures"] == 0
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(f"""# Performance summary (TC-PERF-01, TC-PERF-02)

Generated by `backend/scripts/run_perf.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC.
Machine: {platform.system()} {platform.release()}, Python {platform.python_version()}, SQLite, single uvicorn worker.

## SCW-NF-001: route generation, 200 requests and 20 vehicles

| Run | Time (s) |
|---|---|
""" + "".join(f"| {i + 1} | {t:.2f} |\n" for i, t in enumerate(timings)) + f"""
Target: at most 10 s. Slowest run: {max(timings):.2f} s. **Result: {'PASS' if nf1 else 'FAIL'}**

## SCW-NF-002: API response time, {args.users} concurrent users (Locust, {args.duration} s)

| Measure | Value |
|---|---|
| Peak users | {load['peak_users']} |
| Requests | {load['requests']} |
| Failures | {load['failures']} |
| Median (ms) | {load['median']:.0f} |
| 95th percentile (ms) | {load['p95']:.0f} |
| 99th percentile (ms) | {load['p99']:.0f} |
| Max (ms) | {load['max']:.0f} |

Target: 95% of calls within 2000 ms and no failures. **Result: {'PASS' if nf2 else 'FAIL'}**
""", encoding="utf-8")
    for leftover in BACKEND.glob("perf_*.csv"):
        leftover.unlink()
    print(f"Wrote {REPORT}")


if __name__ == "__main__":
    main()
