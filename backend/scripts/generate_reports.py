"""Build the Part 3 test reports from a real test run.

From the backend folder:
    python scripts/generate_reports.py               -> writes all three into docs/reports/
    python scripts/generate_reports.py --only unit   (or coverage / branch)
    python scripts/generate_reports.py --out some/folder

Reports: unit-test-report.md, code-coverage-report.md, branch-coverage-report.md.
"""

import argparse
import json
import platform
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
DEFAULT_OUT = BACKEND.parent / "docs" / "reports"

# Which test case documents each test file supports.
TEST_FILE_CASES = {
    "test_auth.py": "TC-AUTH-01, TC-AUTH-02, TC-SEC-02",
    "test_users.py": "TC-ADM-01",
    "test_requests_submit.py": "TC-REQ-01, TC-REQ-02",
    "test_requests_admin.py": "TC-REQ-03, TC-REQ-04",
    "test_requests_tracking.py": "TC-REQ-03",
    "test_route_engine.py": "TC-RT-01, TC-RT-02",
    "test_route_engine_facilities.py": "TC-RT-02, TC-RT-04, TC-FAC-01",
    "test_route_engine_performance.py": "TC-PERF-01",
    "test_routes_api.py": "TC-RT-01, TC-RT-02, TC-RT-04, TC-VEH-01, TC-AUTH-02",
    "test_routes_driver.py": "TC-RT-03",
    "test_vehicles.py": "TC-VEH-01",
    "test_driver_assignment.py": "TC-VEH-02",
    "test_vehicle_load.py": "TC-RT-02, TC-VEH-02",
    "test_facilities.py": "TC-FAC-01, TC-FAC-02",
    "test_security_lockout.py": "TC-SEC-01",
    "test_transport.py": "TC-SEC-02, TC-SEC-03",
    "test_audit.py": "TC-SEC-04",
    "test_notifications.py": "TC-NOT-01",
    "test_dashboard_reports.py": "TC-RPT-01",
    "test_geo.py": "TC-RT-01",
    "test_health.py": "TC-AVL-01 (health check)",
    "test_web.py": "TC-USE-01 (web app served)",
}


def run_tests(workdir: Path) -> tuple[Path, Path]:
    junit, cov = workdir / "junit.xml", workdir / "coverage.json"
    subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-p", "no:warnings", f"--junitxml={junit}",
         "--cov=app", "--cov-branch", f"--cov-report=json:{cov}"],
        cwd=BACKEND, check=False,
    )
    return junit, cov


def header(title: str) -> str:
    return (f"# {title}\n\nGenerated by `backend/scripts/generate_reports.py` on "
            f"{datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC from a full test run.\n"
            f"Environment: {platform.system()} {platform.release()}, Python {platform.python_version()}, "
            "pytest with pytest-cov, in-memory SQLite. CI runs the same command on every pull request.\n\n")


def unit_report(junit: Path) -> str:
    files = defaultdict(lambda: {"tests": 0, "passed": 0, "failed": 0, "skipped": 0, "time": 0.0, "failures": []})
    for case in ET.parse(junit).getroot().iter("testcase"):
        name = case.get("classname", "").split(".")[-1] + ".py"
        row = files[name]
        row["tests"] += 1
        row["time"] += float(case.get("time", 0))
        if case.find("failure") is not None or case.find("error") is not None:
            row["failed"] += 1
            row["failures"].append(case.get("name"))
        elif case.find("skipped") is not None:
            row["skipped"] += 1
        else:
            row["passed"] += 1
    total = {k: sum(r[k] for r in files.values()) for k in ("tests", "passed", "failed", "skipped")}
    lines = [header("Unit Test Report"), "## Summary\n\n| Tests | Passed | Failed | Skipped | Pass rate |\n|---|---|---|---|---|\n",
             f"| {total['tests']} | {total['passed']} | {total['failed']} | {total['skipped']} | "
             f"{100 * total['passed'] / max(1, total['tests']):.1f}% |\n\n",
             "## By test file\n\n| Test file | Tests | Passed | Failed | Time (s) | Test cases supported |\n|---|---|---|---|---|---|\n"]
    for name in sorted(files):
        r = files[name]
        lines.append(f"| `{name}` | {r['tests']} | {r['passed']} | {r['failed']} | {r['time']:.2f} | {TEST_FILE_CASES.get(name, '-')} |\n")
    failing = [f"- `{n}`: {', '.join(r['failures'])}\n" for n, r in sorted(files.items()) if r["failures"]]
    lines.append("\n## Failures\n\n" + ("".join(failing) if failing else "None. Every test passed.\n"))
    return "".join(lines)


def coverage_rows(cov: Path):
    data = json.loads(cov.read_text())
    for path, info in sorted(data["files"].items()):
        yield path.replace("\\", "/"), info["summary"]


def _total(rows, keys):
    return {k: sum(r[k] for _, r in rows) for k in keys}


def coverage_report(cov: Path) -> str:
    rows = list(coverage_rows(cov))
    service = [(p, s) for p, s in rows if "/services/" in p]
    t_all = _total(rows, ("num_statements", "covered_lines"))
    t_svc = _total(service, ("num_statements", "covered_lines"))
    pct = lambda t: 100 * t["covered_lines"] / max(1, t["num_statements"])  # noqa: E731
    lines = [header("Code Coverage Report"),
             "Statement coverage measured with `pytest --cov=app --cov-branch`.\n\n",
             "## Summary\n\n| Scope | Statements | Covered | Coverage | Target |\n|---|---|---|---|---|\n",
             f"| Service layer (`app/services`) | {t_svc['num_statements']} | {t_svc['covered_lines']} | {pct(t_svc):.1f}% | at least 70% (SCW-NF-005) |\n",
             f"| Whole backend (`app`) | {t_all['num_statements']} | {t_all['covered_lines']} | {pct(t_all):.1f}% | CI fails below 70% |\n\n",
             f"**SCW-NF-005: {'PASS' if pct(t_svc) >= 70 else 'FAIL'}**\n\n",
             "## By file\n\n| File | Statements | Missed | Coverage |\n|---|---|---|---|\n"]
    for path, s in rows:
        lines.append(f"| `{path}` | {s['num_statements']} | {s['missing_lines']} | {s['percent_covered']:.1f}% |\n")
    return "".join(lines)


def branch_report(cov: Path) -> str:
    rows = [(p, s) for p, s in coverage_rows(cov) if s.get("num_branches")]
    t = _total(rows, ("num_branches", "covered_branches", "num_partial_branches"))
    pct = 100 * t["covered_branches"] / max(1, t["num_branches"])
    lines = [header("Branch Coverage Report"),
             "Branch coverage measured with `pytest --cov=app --cov-branch`: every `if`, loop and early return "
             "has two outcomes, and a branch counts as covered when a test takes it.\n\n",
             "## Summary\n\n| Branches | Covered | Partially covered | Branch coverage |\n|---|---|---|---|\n",
             f"| {t['num_branches']} | {t['covered_branches']} | {t['num_partial_branches']} | {pct:.1f}% |\n\n",
             "## By file\n\n| File | Branches | Covered | Partial | Branch coverage |\n|---|---|---|---|---|\n"]
    for path, s in sorted(rows, key=lambda r: r[1]["covered_branches"] / r[1]["num_branches"]):
        lines.append(f"| `{path}` | {s['num_branches']} | {s['covered_branches']} | {s['num_partial_branches']} | "
                     f"{100 * s['covered_branches'] / s['num_branches']:.1f}% |\n")
    lines.append("\nFiles are sorted from lowest to highest, so the gaps to look at first are at the top.\n")
    return "".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", choices=["unit", "coverage", "branch"])
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    args = parser.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        junit, cov = run_tests(Path(tmp))
        reports = {
            "unit": ("unit-test-report.md", lambda: unit_report(junit)),
            "coverage": ("code-coverage-report.md", lambda: coverage_report(cov)),
            "branch": ("branch-coverage-report.md", lambda: branch_report(cov)),
        }
        for key, (name, build) in reports.items():
            if args.only in (None, key):
                (out / name).write_text(build(), encoding="utf-8")
                print(f"Wrote {out / name}")


if __name__ == "__main__":
    main()
